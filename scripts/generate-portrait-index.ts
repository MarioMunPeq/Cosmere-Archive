/**
 * Generate the portrait lookup manifest from the image files that remain in
 * public/characters/. This small task can be run without replaying the one-time
 * content migration.
 *
 * Usage: pnpm portraits:build
 */

import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(here, '..')
const portraitsDir = join(ROOT, 'public', 'characters')
const portraitsFile = join(ROOT, 'src', 'data', 'generated', 'portraits.ts')
const names = readdirSync(portraitsDir)
  .filter((file) => /\.webp$/i.test(file))
  .map((file) => file.replace(/\.webp$/i, ''))
  .sort()

writeFileSync(
  portraitsFile,
  `/**
 * GENERATED by scripts/generate-portrait-index.ts — do not edit.
 *
 * The character portraits that actually exist under public/characters/. The
 * resolver uses this to decide between an <img> and a <Monogram>, so a missing
 * portrait never turns into a network request. Decision D-DATA, M1 block 5.
 *
 * ${names.length} files · regenerate with \`pnpm portraits:build\`
 */

export const PORTRAIT_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)}

const PORTRAIT_SET: ReadonlySet<string> = new Set(PORTRAIT_NAMES)

/** True when public/characters/<Name>.webp exists. */
export function hasPortraitFile(name: string): boolean {
  return PORTRAIT_SET.has(name)
}
`,
  'utf8',
)

console.log(`portrait manifest: ${names.length} files -> src/data/generated/portraits.ts`)
